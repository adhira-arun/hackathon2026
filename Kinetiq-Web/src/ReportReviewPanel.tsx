import { useState } from 'react'

import { generateSummary, saveReview, sendReport, type OtReview, type StoredReport } from './api'

type Props = {
  report: StoredReport
  onUpdated: (report: StoredReport) => void
}

const STATUS_LABELS: Record<OtReview['status'], string> = {
  pending: 'Pending review',
  reviewed: 'Reviewed',
  needs_follow_up: 'Needs follow-up',
}

function List({ title, items }: { title: string; items: string[] }) {
  if (!items.length) return null
  return (
    <div className="ai-list">
      <strong>{title}</strong>
      <ul>
        {items.map((item, i) => (
          <li key={i}>{item}</li>
        ))}
      </ul>
    </div>
  )
}

function ReportReviewPanel({ report, onUpdated }: Props) {
  const [aiLoading, setAiLoading] = useState(false)
  const [aiError, setAiError] = useState('')
  const [notes, setNotes] = useState(report.otReview?.notes ?? '')
  const [saving, setSaving] = useState(false)
  const [message, setMessage] = useState('')

  async function handleGenerate() {
    setAiLoading(true)
    setAiError('')

    try {
      // Make sure the server has this report (older ones may only be local).
      await sendReport(report)
      onUpdated(await generateSummary(report.id))
    } catch (err) {
      setAiError(
        err instanceof Error ? err.message : 'Could not generate the summary.'
      )
    } finally {
      setAiLoading(false)
    }
  }

  async function handleSave(status: OtReview['status']) {
    setSaving(true)
    setMessage('')

    try {
      await sendReport(report)
      onUpdated(await saveReview(report.id, { notes, status }))
      setMessage(`Saved as "${STATUS_LABELS[status]}".`)
    } catch (err) {
      setMessage(
        err instanceof Error ? err.message : 'Could not save your evaluation.'
      )
    } finally {
      setSaving(false)
    }
  }

  const ai = report.aiSummary

  return (
    <>
      <h4>AI-assisted summary</h4>

      {ai ? (
        <div className="ai-summary-card">
          <p>{ai.summary}</p>
          <List title="Observed strengths" items={ai.strengths} />
          <List title="Observations to consider" items={ai.concerns} />
          <List title="Flags for OT" items={ai.flagsForOT} />
          <small>
            Generated by {ai.model} on{' '}
            {new Date(ai.generatedAt).toLocaleString()}. AI-assisted and
            descriptive only. Not a diagnosis. Please verify against the data
            above.
          </small>
        </div>
      ) : (
        <p className="chart-description">
          No AI summary yet. It is generated from the numbers above only. The
          patient's name and video are never sent.
        </p>
      )}

      {aiError && <p className="camera-error">{aiError}</p>}

      <button
        className="secondary-action"
        onClick={handleGenerate}
        disabled={aiLoading}
      >
        {aiLoading
          ? 'Generating…'
          : ai
            ? 'Regenerate summary'
            : 'Generate AI summary'}
      </button>

      <h4>OT evaluation</h4>

      {report.otReview && (
        <p className="chart-description">
          Status: {STATUS_LABELS[report.otReview.status]} · last saved{' '}
          {new Date(report.otReview.reviewedAt).toLocaleString()}
        </p>
      )}

      <textarea
        className="ot-notes"
        rows={5}
        maxLength={5000}
        value={notes}
        onChange={(e) => setNotes(e.target.value)}
        placeholder="Add your clinical notes and evaluation for this session…"
      />

      <div className="review-actions">
        <button
          className="primary-action"
          disabled={saving}
          onClick={() => handleSave('reviewed')}
        >
          Mark as reviewed
        </button>
        <button
          className="secondary-action"
          disabled={saving}
          onClick={() => handleSave('needs_follow_up')}
        >
          Needs follow-up
        </button>
      </div>

      {message && <p className="chart-description">{message}</p>}
    </>
  )
}

export default ReportReviewPanel